import pandas as pd

# Create dummy dataset
data = {
    "Patient_ID": [
        "P001", "P002", "P003", "P004", "P005",
        "P006", "P007", "P008", "P009", "P010",
        "P011", "P012", "P013", "P014", "P015"
    ],
    "Age": [
        22, 45, 51, 28, 39, 60, 33, 47, 25, 55,
        42, 36, 62, 30, 49
    ],
    "BMI": [
        21.5, 29.2, 31.0, 23.1, 27.5, 32.4, 24.0,
        28.5, 22.3, 30.1, 26.8, 25.5, 33.0, 23.8, 29.0
    ],
    "Glucose": [
        88, 145, 170, 95, 125, 185, 99, 155, 91,
        165, 118, 108, 190, 94, 140
    ],
    "Family_History": [
        "No", "Yes", "Yes", "No", "Yes", "Yes",
        "No", "No", "No", "Yes", "No", "Yes",
        "Yes", "No", "Yes"
    ]
}

df = pd.DataFrame(data)


# Calculate risk score
def calculate_risk(age, bmi, glucose, family_history):
    score = 0
    reasons = []

    if glucose >= 126:
        score += 3
        reasons.append("High glucose level")
    elif glucose >= 100:
        score += 1
        reasons.append("Elevated glucose level")

    if bmi >= 30:
        score += 2
        reasons.append("High BMI")
    elif bmi >= 25:
        score += 1
        reasons.append("BMI in overweight range")

    if age >= 45:
        score += 1
        reasons.append("Age-related risk factor")

    if family_history.lower() == "yes":
        score += 1
        reasons.append("Family history of diabetes")

    return score, reasons


# Predict risk category
def predict_risk(age, bmi, glucose, family_history):
    score, reasons = calculate_risk(
        age, bmi, glucose, family_history
    )

    if score >= 4:
        category = "High Risk"
    elif score >= 2:
        category = "Moderate Risk"
    else:
        category = "Low Risk"

    return score, category, reasons


# Analyze all patients
def analyze_dataset():
    results = []

    for _, patient in df.iterrows():
        score, category, reasons = predict_risk(
            patient["Age"],
            patient["BMI"],
            patient["Glucose"],
            patient["Family_History"]
        )

        results.append({
            "Patient_ID": patient["Patient_ID"],
            "Risk_Score": score,
            "Risk_Category": category
        })

    result_df = pd.DataFrame(results)

    print("\nPatient Risk Analysis")
    print(result_df.to_string(index=False))

    print("\nRisk Category Summary")
    print(result_df["Risk_Category"].value_counts())

    print("\nAverage glucose:", round(df["Glucose"].mean(), 2))
    print("Average BMI:", round(df["BMI"].mean(), 2))


# Check a new patient
def check_new_patient():
    try:
        age = int(input("Enter age: "))
        bmi = float(input("Enter BMI: "))
        glucose = float(input("Enter fasting glucose (mg/dL): "))
        family_history = input(
            "Family history of diabetes (Yes/No): "
        ).strip().lower()

        if age <= 0 or bmi <= 0 or glucose < 0:
            print("Please enter valid measurements.")
            return

        if family_history not in ["yes", "no"]:
            print("Enter Yes or No for family history.")
            return

        score, category, reasons = predict_risk(
            age, bmi, glucose, family_history
        )

        print("\nPrediction Result")
        print("Risk Score:", score)
        print("Risk Category:", category)

        if reasons:
            print("\nContributing factors:")
            for reason in reasons:
                print("-", reason)
        else:
            print("No risk factors flagged by these rules.")

        print("\nThis is an educational demo, not a medical diagnosis.")

    except ValueError:
        print("Please enter valid numeric values.")


# Display menu
def main():
    while True:
        print("\nDiabetes Risk Prediction System")
        print("1. View dataset")
        print("2. Analyze all patients")
        print("3. Check a new patient")
        print("4. Exit")

        choice = input("Enter your choice: ")

        if choice == "1":
            print(df.to_string(index=False))
        elif choice == "2":
            analyze_dataset()
        elif choice == "3":
            check_new_patient()
        elif choice == "4":
            print("Goodbye!")
            break
        else:
            print("Invalid choice. Try again.")


if __name__ == "__main__":
    main()